/**
 * Regenerates src/crossword/themes/index.ts from the theme files in that folder.
 * Run after adding or removing a theme:  npx tsx scripts/build-theme-index.ts
 */
import { readdirSync, writeFileSync } from 'fs';
import path from 'path';

const dir = path.resolve(import.meta.dirname, '../src/crossword/themes');
const files = readdirSync(dir)
  .filter((f) => f.endsWith('.ts') && f !== 'index.ts')
  .map((f) => f.replace(/\.ts$/, ''))
  .sort();

const ident = (id: string) => id.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase()).replace(/^[0-9]/, '_$&');

const src = `// AUTO-GENERATED by scripts/build-theme-index.ts – do not edit by hand.
import type { Theme } from '../types';
${files.map((f) => `import ${ident(f)} from './${f}';`).join('\n')}

export const THEMES: Theme[] = [
${files.map((f) => `  ${ident(f)},`).join('\n')}
];
`;
writeFileSync(path.join(dir, 'index.ts'), src);
console.log(`Wrote index with ${files.length} themes`);
